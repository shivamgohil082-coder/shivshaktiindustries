import { NextRequest, NextResponse } from 'next/server';
import { requireAdminSession } from '@/lib/auth';
import { getAllProducts, getAllEnquiries, getContentBlocks, getSeoMetaList } from '@/lib/db';

export async function GET(req: NextRequest) {
  const session = requireAdminSession(req);
  if (!session) {
    return NextResponse.json({ success: false, error: 'Not found' }, { status: 404 });
  }

  try {
    const { searchParams } = new URL(req.url);
    const format = searchParams.get('format') || 'json';
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);

    const products = await getAllProducts(false);
    const enquiries = await getAllEnquiries();
    const content = await getContentBlocks();
    const seo = await getSeoMetaList();

    if (format === 'sql') {
      let sql = `-- =====================================================================\n`;
      sql += `-- SHIV SHAKTI INDUSTRIES — DATABASE BACKUP\n`;
      sql += `-- Generated: ${new Date().toISOString()}\n`;
      sql += `-- Generated By: ${session.username}\n`;
      sql += `-- =====================================================================\n\n`;

      sql += `-- Table: products (${products.length} records)\n`;
      for (const p of products) {
        const cleanName = (p.name || '').replace(/'/g, "''");
        const cleanDesc = (p.description || '').replace(/'/g, "''");
        const cleanSpecs = (p.specs || '').replace(/'/g, "''");
        sql += `INSERT INTO \`products\` (\`name\`,\`slug\`,\`category\`,\`tolerance\`,\`material\`,\`image\`,\`is_published\`,\`description\`,\`specs\`) VALUES ('${cleanName}','${p.slug}','${p.category}','${p.tolerance || ''}','${p.material || ''}','${p.image}',${p.is_published ? 1 : 0},'${cleanDesc}','${cleanSpecs}') ON DUPLICATE KEY UPDATE \`name\`=VALUES(\`name\`);\n`;
      }

      sql += `\n-- Table: enquiries (${enquiries.length} records)\n`;
      for (const e of enquiries) {
        const cleanSubject = (e.subject || '').replace(/'/g, "''");
        const cleanMsg = (e.message || '').replace(/'/g, "''");
        sql += `INSERT INTO \`enquiries\` (\`reference_no\`,\`type\`,\`full_name\`,\`email\`,\`phone\`,\`subject\`,\`message\`,\`status\`) VALUES ('${e.reference_no}','${e.type}','${e.full_name}','${e.email}','${e.phone || ''}','${cleanSubject}','${cleanMsg}','${e.status}') ON DUPLICATE KEY UPDATE \`status\`=VALUES(\`status\`);\n`;
      }

      return new NextResponse(sql, {
        status: 200,
        headers: {
          'Content-Type': 'application/sql',
          'Content-Disposition': `attachment; filename="ssi-backup-${timestamp}.sql"`,
        },
      });
    }

    const backupData = {
      version: '1.0.0',
      exported_at: new Date().toISOString(),
      exported_by: session.username,
      database: {
        products,
        enquiries,
        content_blocks: content,
        seo_meta: seo,
      },
    };

    return new NextResponse(JSON.stringify(backupData, null, 2), {
      status: 200,
      headers: {
        'Content-Type': 'application/json',
        'Content-Disposition': `attachment; filename="ssi-backup-${timestamp}.json"`,
      },
    });
  } catch (error) {
    console.error('Backup generation error:', error);
    return NextResponse.json({ success: false, error: 'Failed to generate backup.' }, { status: 500 });
  }
}
